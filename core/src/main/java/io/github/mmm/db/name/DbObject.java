package io.github.mmm.db.name;

import java.util.Collection;
import java.util.List;

import io.github.mmm.base.io.UncheckedAppendable;
import io.github.mmm.base.lang.ToString;
import io.github.mmm.db.ddl.column.DbColumn;
import io.github.mmm.db.ddl.constraint.DbConstraint;
import io.github.mmm.db.ddl.index.DbIndex;
import io.github.mmm.db.ddl.table.DbTable;

/// Database object with a [name][#getName()]. A database object can represent one of the following things:
///
/// - [DbTable] (including view, synonym, or materialized view)
/// - [DbColumn]
/// - [DbConstraint]
/// - [DbIndex]
///
/// Please note that a [DbObject] can also be a create statement. In such case the represented object may not physically exist in the database (yet).
///
/// @since 1.0.0
public interface DbObject extends ToString {

  /// @return the name of this [DbObject]. May be be `null`. Use [#getName()] or [#getName(DbNamingStrategy)] to get the proper name with auto-generation if the
  ///         raw name is not available.
  DbQualifiedName getRawName();

  /// @return the name of this [DbObject]. Shall never be `null`.
  default DbQualifiedName getName() {

    return getName(DbNamingStrategy.of());
  }

  /// @param namingStrategy the [DbNamingStrategy] to use. May be `null` to get the raw name. For some kind of database objects (e.g. [DbConstraint] or
  ///        [DbIndex]) the raw name may even be `null` and will then be auto-generated by the naming strategy.
  /// @return the [name][#getName()] formatted or even auto-generated using the given [DbNamingStrategy]. If the given [DbNamingStrategy] is `null`, this method
  ///         return the raw name that can even be `null` in cases described above.
  default DbQualifiedName getName(DbNamingStrategy namingStrategy) {

    return namingStrategy.getName(this);
  }

  /// @return `true` if the name is derived from the Java world (e.g. [simple class name][Class#getSimpleName()]), `false` otherwise (already specific for
  ///         database).
  /// @see io.github.mmm.bean.BeanType#getStableName()
  /// @see io.github.mmm.bean.BeanType#getSimpleName()
  default boolean hasJavaName() {

    return false;
  }

  /// @param values the [Collection] with the values to append.
  /// @param appendable the [UncheckedAppendable].
  /// @param mode the mode of the string format.
  /// @see #toString(UncheckedAppendable, int)
  static void append(Collection<?> values, UncheckedAppendable appendable, int mode) {

    if (values == null) {
      values = List.of();
    }
    appendable.append('(');
    boolean first = true;
    for (Object value : values) {
      if (value instanceof ToString ts) {
        ts.toString(appendable, mode);
      } else {
        appendable.append(value);
      }
      if (first) {
        first = false;
      } else {
        appendable.append(',');
      }
    }
    appendable.append(')');
  }

}
